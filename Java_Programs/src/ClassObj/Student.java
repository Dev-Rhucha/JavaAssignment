package ClassObj;

public class Student {
	
	 int studentid;
	    String name;
	    int age;
	    String course;
	    int marks;

	    void display()
	    {
	        System.out.println("Student Id is: " + this.studentid);
	        System.out.println("Name is: " + this.name);
	        System.out.println("Age is: " + this.age);
	        System.out.println("Course is: " + this.course);
	        System.out.println("Marks are: " + this.marks);
	    }

}
